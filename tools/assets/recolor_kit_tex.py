#!/usr/bin/env python3
"""Recolour a village-kit base-colour sheet to a target colour, keeping its detail.

The Quaternius village kit ships ONE red tile sheet and ONE tan brick sheet,
and every roof and wall in every city is drawn from them. A per-instance tint
is a MULTIPLY, so it can only darken: it turns the red roof a duller red, never
slate, and never moss. MEASURED (this script's --measure): T_FlatTiles averages
#8b381a, T_RoundTiles #b2532f, T_UnevenBrick #877865 -- red-dominant sheets
whose green and blue channels cannot be multiplied UP.

So a city that is not red-roofed needs its own sheet. This keeps each pixel's
LUMINANCE (the grout lines, the tile edges, the weathering) and replaces its
colour with the target, scaled so the sheet's mean lands on the target:

    out = target * (L / mean(L)) ** gamma

`town.ts` swaps these in per palette (setPalette) on cloned materials, so the
kit's own files are never touched and Moonmere keeps its red.

Run:  python3 tools/assets/recolor_kit_tex.py            # regenerate SHEETS
      python3 tools/assets/recolor_kit_tex.py slate      # only the outputs naming it
      python3 tools/assets/recolor_kit_tex.py caerdun    # a palette's sheets (ALIASES)
      python3 tools/assets/recolor_kit_tex.py --measure  # print the means

A name that matches no output is an error, not a silent no-op.

Regenerate only the sheets you changed: the outputs are tracked JPEGs, and a
re-encode under a different Pillow rewrites every one of them byte for byte
even when nothing about its colour moved.
"""
import os
import sys
import numpy as np
from PIL import Image

TOWN = os.path.join(os.path.dirname(__file__), "..", "..", "client", "public", "models", "town")

# (source sheet, output sheet, target mean colour, gamma)
#   granite  Caerdun's walls: the Fields postcard's granite #8b8f96, pulled a
#            touch darker since the wall's plaster trim and the sky lift it
#   slate    Caerdun's roofs: cold blue-grey, darker than the walls so the
#            skyline reads as roofs over stone rather than one grey mass
#   moss     Heartwood's roofs: olive-brown, the round tile gone green under
#            three centuries of canopy drip
SHEETS = [
    ("T_UnevenBrick_BaseColor.jpg", "T_UnevenBrick_BaseColor_granite.jpg", "#84888e", 1.0),
    ("T_FlatTiles_BaseColor.jpg", "T_FlatTiles_BaseColor_slate.jpg", "#525a66", 0.9),
    ("T_RoundTiles_BaseColor.jpg", "T_RoundTiles_BaseColor_moss.jpg", "#6e7a45", 0.9),
    # and each city's OTHER tile, for the pieces that only come in one: the
    # gatehouse and tower cones are round-tiled, the kit's dormers flat
    ("T_RoundTiles_BaseColor.jpg", "T_RoundTiles_BaseColor_slate.jpg", "#525a66", 0.9),
    ("T_FlatTiles_BaseColor.jpg", "T_FlatTiles_BaseColor_moss.jpg", "#6e7a45", 0.9),
]

# a palette's name for the outputs it draws (town.ts), so the palette can be
# regenerated by the name the code calls it
ALIASES = {"caerdun": ["granite", "slate"], "heartwood": ["moss"]}


def hex_rgb(h):
    h = h.lstrip("#")
    return np.array([int(h[i:i + 2], 16) for i in (0, 2, 4)], dtype=float)


def mean_hex(path):
    im = np.asarray(Image.open(path).convert("RGB")).astype(float)
    m = im.reshape(-1, 3).mean(0)
    return "#%02x%02x%02x" % tuple(int(v) for v in m)


def recolor(src, dst, target, gamma):
    im = np.asarray(Image.open(src).convert("RGB")).astype(float) / 255.0
    lum = im @ np.array([0.2126, 0.7152, 0.0722])
    rel = (lum / max(1e-6, lum.mean())) ** gamma
    out = np.clip(rel[..., None] * (hex_rgb(target) / 255.0)[None, None, :], 0, 1)
    Image.fromarray((out * 255 + 0.5).astype(np.uint8)).save(dst, quality=88)
    print(f"{os.path.basename(dst)}: mean {mean_hex(dst)} (target {target})")


if __name__ == "__main__":
    if "--measure" in sys.argv:
        for f in sorted(os.listdir(TOWN)):
            if f.startswith("T_") and f.endswith("_BaseColor.jpg"):
                print(f, mean_hex(os.path.join(TOWN, f)))
        sys.exit(0)
    only = [n for a in sys.argv[1:] if not a.startswith("-") for n in ALIASES.get(a, [a])]
    picked = [s for s in SHEETS if not only or any(o in s[1] for o in only)]
    if not picked:
        sys.exit(f"no sheet in SHEETS names any of {only}")
    for src, dst, target, gamma in picked:
        recolor(os.path.join(TOWN, src), os.path.join(TOWN, dst), target, gamma)
